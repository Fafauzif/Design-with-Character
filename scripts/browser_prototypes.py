"""Offline journeys for the five original interactive works."""
from playwright.sync_api import expect


def run(page, open_style):
    open_style("halftone-dossier")
    opener = page.locator("#open-file")
    opener.press("Enter")
    expect(page.locator("#case-title")).to_be_focused()
    expect(page.locator("#file-report")).to_be_disabled()
    for note in page.locator(".note summary").all():
        note.press("Enter")
        expect(note.locator("..")).to_have_attribute("open", "")
    expect(page.locator("#file-report")).to_be_enabled()
    page.locator("#file-report").press("Enter")
    expect(page.locator("#result")).to_be_visible()
    expect(page.locator("#result")).to_be_focused()
    page.keyboard.press("Escape")
    expect(opener).to_be_focused()
    page.reload()
    opener.press("Enter")
    expect(page.locator("#result")).to_be_visible()

    open_style("botanical-letterpress")
    toggle = page.locator("#folio-toggle")
    toggle.press("Enter")
    expect(toggle).to_have_attribute("aria-expanded", "true")
    expect(page.locator("#field-note")).to_be_visible()
    expect(page.locator("#note-heading")).to_be_focused()
    page.keyboard.press("Escape")
    expect(toggle).to_have_attribute("aria-expanded", "false")
    expect(toggle).to_be_focused()

    open_style("specimen-cabinet")
    drawers = page.locator(".drawer summary")
    drawers.first.press("Enter")
    keep = page.locator(".drawer").first.locator(".keep")
    keep.press("Enter")
    expect(keep).to_have_attribute("data-kept", "true")
    drawers.nth(1).press("Enter")
    expect(page.locator(".drawer[open]")).to_have_count(1)
    page.reload()
    expect(page.locator("#note-count")).to_contain_text("1")
    page.locator("#notes summary").press("Enter")
    page.locator("#note-list button").first.press("Enter")
    expect(drawers.first).to_be_focused()
    keep.press("Enter")
    expect(keep).to_have_attribute("data-kept", "false")

    open_style("arcade-workshop")
    expect(page.locator(".pad")).to_have_count(24)
    page.get_by_role("button", name="Empty pattern").press("Enter")
    expect(page.locator(".pad[aria-pressed=true]")).to_have_count(0)
    pad = page.locator(".pad").first
    pad.press("Enter")
    expect(pad).to_have_attribute("aria-pressed", "true")
    expect(pad).to_be_focused()
    page.get_by_role("button", name="Bounce").press("Enter")
    expect(page.locator(".pad[aria-pressed=true]")).not_to_have_count(0)
    tempo = page.locator("#tempo")
    tempo.press("End")
    expect(tempo).to_have_attribute("aria-valuetext", "200 beats per minute")
    page.locator("#play").press("Enter")
    expect(page.locator("#play")).to_have_attribute("data-playing", "true")
    expect(page.locator(".step[data-current=true]")).to_have_count(1)
    page.locator("#tray-stop").press("Enter")
    expect(page.locator("#play")).to_have_attribute("data-playing", "false")
    if page.evaluate("matchMedia('(prefers-reduced-motion: reduce)').matches"):
        expect(page.locator(".pattern-tray")).not_to_have_class("pattern-tray unseen")
        for item in page.locator(".preset").all():
            expect(item).to_have_css("opacity", "1")

    page.clock.install()
    open_style("pixel-study-room")
    canvas = page.locator("#room")
    before = canvas.evaluate("canvas => canvas.toDataURL()")
    page.get_by_role("button", name="5 min", exact=True).press("Enter")
    expect(page.locator("#clock")).to_have_text("05:00")
    page.locator("#action").press("Enter")
    expect(page.locator("#status")).to_have_text("Focusing")
    if canvas.evaluate("canvas => canvas.toDataURL()") == before:
        raise AssertionError("Starting the session did not change the study room")
    page.clock.fast_forward(3200)
    page.locator("#action").press("Enter")
    expect(page.locator("#status")).to_have_text("Paused")
    paused_time = page.locator("#clock").text_content()
    page.reload()
    expect(page.locator("#clock")).to_have_text(paused_time)
    expect(page.locator("#status")).to_have_text("Paused")
    page.locator("#action").press("Enter")
    page.clock.fast_forward(305000)
    expect(page.locator("#status")).to_have_text("Session complete")
    expect(page.locator("#clock")).to_have_text("00:00")
    page.locator("#reset").press("Enter")
    expect(page.locator("#action")).to_be_focused()
    page.clock.resume()
